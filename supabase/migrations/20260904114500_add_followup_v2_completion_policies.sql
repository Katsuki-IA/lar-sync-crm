create or replace function public.claim_followup_completion_events_v2(
  p_worker_id text,
  p_limit integer default 10
)
returns setof public.followup_completion_events_v2
language plpgsql
set search_path to ''
as $function$
begin
  if nullif(btrim(p_worker_id), '') is null then
    raise exception 'worker_id is required';
  end if;

  return query
  with candidates as (
    select e.id
    from public.followup_completion_events_v2 e
    where e.scheduled_at <= now()
      and e.attempts < e.max_attempts
      and (
        e.status = 'pending'
        or (e.status = 'processing' and e.claimed_at < now() - interval '15 minutes')
      )
    order by e.scheduled_at, e.id
    for update skip locked
    limit greatest(1, least(coalesce(p_limit, 10), 100))
  )
  update public.followup_completion_events_v2 e
     set status = 'processing',
         claimed_at = now(),
         claimed_by = btrim(p_worker_id),
         attempts = e.attempts + 1,
         updated_at = now()
    from candidates c
   where e.id = c.id
  returning e.*;
end;
$function$;

create or replace function public.complete_followup_completion_event_v2(
  p_event_id bigint,
  p_worker_id text,
  p_success boolean,
  p_error text default null,
  p_retryable boolean default true
)
returns jsonb
language plpgsql
set search_path to ''
as $function$
declare
  v_event public.followup_completion_events_v2%rowtype;
  v_next_status text;
begin
  select * into v_event
  from public.followup_completion_events_v2 e
  where e.id = p_event_id
  for update;

  if not found then
    return jsonb_build_object('updated', false, 'reason', 'event_not_found');
  end if;

  if v_event.status <> 'processing' or v_event.claimed_by is distinct from btrim(p_worker_id) then
    return jsonb_build_object('updated', false, 'reason', 'event_not_owned');
  end if;

  v_next_status := case
    when p_success then 'succeeded'
    when p_retryable and v_event.attempts < v_event.max_attempts then 'pending'
    else 'dead'
  end;

  update public.followup_completion_events_v2
     set status = v_next_status,
         scheduled_at = case
           when v_next_status = 'pending'
             then now() + make_interval(mins => least(60, (5 * power(2, greatest(v_event.attempts - 1, 0)))::integer))
           else scheduled_at
         end,
         processed_at = case when v_next_status in ('succeeded', 'dead') then now() else null end,
         last_error = case when p_success then null else left(coalesce(p_error, 'Falha sem detalhes.'), 5000) end,
         claimed_at = null,
         claimed_by = null,
         updated_at = now()
   where id = p_event_id;

  return jsonb_build_object(
    'updated', true,
    'event_id', p_event_id,
    'status', v_next_status,
    'attempts', v_event.attempts,
    'max_attempts', v_event.max_attempts
  );
end;
$function$;

revoke all on function public.claim_followup_completion_events_v2(text, integer) from public, anon, authenticated;
