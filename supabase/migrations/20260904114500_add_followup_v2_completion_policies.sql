create table public.followup_completion_policies_v2 (
  id bigint generated by default as identity primary key,
  sequence_id bigint not null references public.followup_sequences_v2(id) on delete cascade,
  enabled boolean not null default false,
  qualified_enabled boolean not null default false,
  qualified_mark_as_lost boolean not null default false,
  qualified_send_to_queue boolean not null default false,
  qualified_queue_id text,
  qualified_tags text[] not null default '{}'::text[],
  unqualified_enabled boolean not null default false,
  unqualified_mark_as_lost boolean not null default true,
  unqualified_send_to_queue boolean not null default false,
  unqualified_queue_id text,
  unqualified_tags text[] not null default '{}'::text[],
  cancellation_reason_id text,
  cancellation_reason_name text,
  dispatch_delay_minutes integer not null default 0,
  max_attempts smallint not null default 3,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint followup_completion_policies_v2_sequence_uidx unique (sequence_id),
  constraint followup_completion_policies_v2_delay_check
    check (dispatch_delay_minutes between 0 and 10080),
  constraint followup_completion_policies_v2_attempts_check
    check (max_attempts between 1 and 10),
  constraint followup_completion_policies_v2_qualified_queue_check
    check (
      not enabled
      or not qualified_enabled
      or not qualified_send_to_queue
      or nullif(btrim(qualified_queue_id), '') is not null
    ),
  constraint followup_completion_policies_v2_unqualified_queue_check
    check (
      not enabled
      or not unqualified_enabled
      or not unqualified_send_to_queue
      or nullif(btrim(unqualified_queue_id), '') is not null
    )
);

create index followup_completion_policies_v2_enabled_idx
  on public.followup_completion_policies_v2 (sequence_id)
  where enabled;

create trigger followup_completion_policies_v2_set_updated_at
before update on public.followup_completion_policies_v2
for each row execute function public.handle_updated_at();

create table public.followup_completion_events_v2 (
  id bigint generated by default as identity primary key,
  policy_id bigint not null references public.followup_completion_policies_v2(id) on delete restrict,
  sequence_id bigint not null references public.followup_sequences_v2(id) on delete restrict,
  enrollment_id bigint references public.followup_enrollments_v2(id) on delete set null,
  final_dispatch_id bigint not null references public.followup_dispatches_v2(id) on delete restrict,
  lead_id bigint not null references public.lead(id) on delete restrict,
  id_empresa bigint not null references public.empresa_dados(id) on delete restrict,
  classification text not null,
  status text not null default 'pending',
  scheduled_at timestamptz not null default now(),
  attempts smallint not null default 0,
  max_attempts smallint not null default 3,
  claimed_at timestamptz,
  claimed_by text,
  processed_at timestamptz,
  last_error text,
  payload_snapshot jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint followup_completion_events_v2_dispatch_uidx unique (final_dispatch_id),
  constraint followup_completion_events_v2_classification_check
    check (classification in ('qualified', 'unqualified')),
  constraint followup_completion_events_v2_status_check
    check (status in ('pending', 'processing', 'succeeded', 'dead')),
  constraint followup_completion_events_v2_attempts_check
    check (attempts >= 0 and max_attempts between 1 and 10)
);

create index followup_completion_events_v2_claim_idx
  on public.followup_completion_events_v2 (scheduled_at, id)
  where status = 'pending';

create index followup_completion_events_v2_company_lead_idx
  on public.followup_completion_events_v2 (id_empresa, lead_id, created_at desc);

create trigger followup_completion_events_v2_set_updated_at
before update on public.followup_completion_events_v2
for each row execute function public.handle_updated_at();

