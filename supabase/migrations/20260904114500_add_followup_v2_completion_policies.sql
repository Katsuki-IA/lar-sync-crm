create or replace function public.accept_followup_attempt_v2(
  p_attempt_id bigint,
  p_meta_message_id text,
  p_meta_response jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
set search_path to ''
as $function$
declare
  v_attempt public.followup_attempts_v2%rowtype;
  v_dispatch public.followup_dispatches_v2%rowtype;
  v_next_step integer;
  v_policy public.followup_completion_policies_v2%rowtype;
  v_lead public.lead%rowtype;
  v_classification text;
  v_action_enabled boolean;
  v_mark_as_lost boolean;
  v_send_to_queue boolean;
  v_queue_id text;
  v_tags text[];
  v_event_id bigint;
  v_current_step_order integer;
  v_current_step_situation bigint;
begin
  if nullif(btrim(p_meta_message_id), '') is null then
    raise exception 'meta_message_id is required';
  end if;

  select * into v_attempt
  from public.followup_attempts_v2 a
  where a.id = p_attempt_id
  for update;

  if not found then
    return jsonb_build_object('accepted', false, 'reason', 'attempt_not_found');
  end if;

  if v_attempt.status <> 'preparing' then
    return jsonb_build_object(
      'accepted', false,
      'reason', 'attempt_not_preparing',
      'status', v_attempt.status
    );
  end if;

  select * into v_dispatch
  from public.followup_dispatches_v2 d
  where d.id = v_attempt.dispatch_id
  for update;

  update public.wa_messages
     set message_id = p_meta_message_id,
         status_current = 'accepted',
         status_last_at = now(),
         raw = coalesce(raw, '{}'::jsonb) || jsonb_build_object('meta_response', coalesce(p_meta_response, '{}'::jsonb)),
         updated_at = now()
   where id = v_attempt.wa_message_id;

  update public.followup_attempts_v2
     set meta_message_id = p_meta_message_id,
         status = 'accepted',
         accepted_at = now(),
         meta_response = coalesce(p_meta_response, '{}'::jsonb),
         updated_at = now()
   where id = p_attempt_id;

  update public.followup_dispatches_v2
     set status = 'accepted',
         sent_to_meta_at = now(),
         updated_at = now()
   where id = v_dispatch.id;

  select st.step_order, st.id_situacao
    into v_current_step_order, v_current_step_situation
  from public.followup_steps_v2 st
  where st.id = v_dispatch.step_id;

  select min(st.step_order)
    into v_next_step
  from public.followup_steps_v2 st
  where st.sequence_id = v_dispatch.sequence_id
    and st.is_active = true
    and st.step_order > v_current_step_order;

  if v_next_step is null then
    update public.followup_enrollments_v2
       set status = 'completed',
           completed_at = now(),
           last_evaluated_at = now(),
           updated_at = now()
     where id = v_dispatch.enrollment_id;

    select * into v_policy
    from public.followup_completion_policies_v2 p
    where p.sequence_id = v_dispatch.sequence_id
      and p.enabled = true;

    if found then
      select * into v_lead
      from public.lead l
      where l.id = v_dispatch.lead_id;

      v_classification := case when coalesce(v_lead.qualificado, 0) = 1 then 'qualified' else 'unqualified' end;

      if v_classification = 'qualified' then
        v_action_enabled := v_policy.qualified_enabled;
        v_mark_as_lost := v_policy.qualified_mark_as_lost;
        v_send_to_queue := v_policy.qualified_send_to_queue;
        v_queue_id := nullif(btrim(v_policy.qualified_queue_id), '');
        v_tags := v_policy.qualified_tags;
      else
        v_action_enabled := v_policy.unqualified_enabled;
        v_mark_as_lost := v_policy.unqualified_mark_as_lost;
        v_send_to_queue := v_policy.unqualified_send_to_queue;
        v_queue_id := nullif(btrim(v_policy.unqualified_queue_id), '');
        v_tags := v_policy.unqualified_tags;
      end if;

      if v_action_enabled then
        insert into public.followup_completion_events_v2 (
          policy_id,
          sequence_id,
          enrollment_id,
          final_dispatch_id,
          lead_id,
          id_empresa,
          classification,
          scheduled_at,
          max_attempts,
          payload_snapshot
        ) values (
          v_policy.id,
          v_dispatch.sequence_id,
          v_dispatch.enrollment_id,
          v_dispatch.id,
          v_dispatch.lead_id,
          v_dispatch.id_empresa,
          v_classification,
          now() + make_interval(mins => v_policy.dispatch_delay_minutes),
          v_policy.max_attempts,
          jsonb_build_object(
            'classification', v_classification,
            'mark_as_lost', v_mark_as_lost,
            'send_to_queue', v_send_to_queue,
            'queue_id', v_queue_id,
            'additional_tags', to_jsonb(coalesce(v_tags, '{}'::text[])),
            'cancellation_reason_id', nullif(btrim(v_policy.cancellation_reason_id), ''),
            'cancellation_reason_name', nullif(btrim(v_policy.cancellation_reason_name), ''),
            'id_empreendimento', v_dispatch.id_empreendimento,
            'final_step_id', v_dispatch.step_id,
            'final_step_order', v_current_step_order,
            'final_step_situation_id', v_current_step_situation
          )
        )
        on conflict (final_dispatch_id) do nothing
        returning id into v_event_id;
      end if;
    end if;
  else
    update public.followup_enrollments_v2
       set next_step_order = v_next_step,
           last_evaluated_at = now(),
           updated_at = now()
     where id = v_dispatch.enrollment_id;
  end if;

  update public.lead
     set etapa_conversa = coalesce(v_next_step, etapa_conversa + 1),
         ult_message = now()::text,
         updated_at = now()
   where id = v_dispatch.lead_id;

  return jsonb_build_object(
    'accepted', true,
    'attempt_id', p_attempt_id,
    'dispatch_id', v_dispatch.id,
    'meta_message_id', p_meta_message_id,
    'next_step_order', v_next_step,
    'enrollment_completed', v_next_step is null,
    'completion_event_id', v_event_id
  );
end;
$function$;

